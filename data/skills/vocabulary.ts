/**
 * Hand-curated skills vocabulary for the on-device "application preparation checklist" extractor.
 *
 * Provenance: every entry below was written by the project authors from general familiarity with
 * New Zealand job advertising. It is original work and is NOT copied or derived from any licensed
 * taxonomy (O*NET, ESCO, ANZSCO, Lightcast or similar). It deliberately complements the separately
 * generated O*NET software list, so ordinary commercial software products are only listed in
 * `supplementalTools`, and only when NZ ads commonly write them in a short or local form.
 *
 * How matching works (src/local-engine/prep.ts):
 * - A requirement statement is split into word tokens; letters and digits stay together with the
 *   symbols that belong to technology names (C++, C#, .NET, Node.js), while spaces, hyphens,
 *   slashes, "&" and commas only separate tokens. Each alias or pattern is tokenised the same way
 *   and must match a run of consecutive tokens, so "health & safety" also matches
 *   "health and safety" only if both spellings are listed. An alias that tokenisation would alter
 *   (such as "Act!") is skipped rather than matched loosely.
 * - `knowledgeAreas` and `softSkills` patterns are lowercase and match regardless of case. Nothing
 *   is stemmed, so singular/plural and NZ/US spelling variants are listed explicitly. Phrases are
 *   chosen so that a single common word never triggers a chip on its own.
 * - `programmingLanguages` and `supplementalTools`: aliases ignore case unless `caseSensitive` is
 *   true (aliases that are also ordinary English words, names or single letters). Case-sensitive
 *   language aliases such as "C", "R" or "Go" count only beside another named technology.
 * - `materials`: each pattern is a case-insensitive regular-expression source string (no flags),
 *   tested against a single requirement sentence. Patterns require applicant-facing wording
 *   ("attach your portfolio", "two professional referees") so job duties do not trigger them.
 * - `label` is the displayed text. The checklist stays in English, like the ad and the CV.
 */

/** Field knowledge areas. `label` is the English chip text shown to users (sentence case, as a NZ recruiter would write it). `patterns` are lowercase English phrases matched as whole tokens, ignoring case; plural/singular variants and common spelling variants (organisation/organization, licence/license) must be listed explicitly; never a single very common word that would match unrelated sentences (e.g. not "care", "data", "sales", "service", "safety" alone). */
export interface KnowledgeArea {
  label: string;
  patterns: string[];
}

/** Personal qualities and transferable skills. */
export interface SoftSkill {
  label: string;
  patterns: string[];
}

/** Programming / query / scripting languages: canonical display label plus case-sensitive aliases as they appear in ads. */
export interface Language {
  label: string;
  aliases: string[];
  caseSensitive?: boolean;
}

/** Human languages. Names that are also nationality adjectives ("Japanese cars") count only
 * when the statement is about language ("fluent", "speak", "communicate in"). */
export interface SpokenLanguage {
  label: string;
  aliases: string[];
  /** Unambiguous names such as "te reo Māori" need no language wording around them. */
  standalone?: boolean;
}

/** Tools and platforms common in NZ ads but missing from or awkwardly named in O*NET. */
export interface Tool {
  label: string;
  aliases: string[];
  caseSensitive?: boolean;
}

/** Application materials an applicant must prepare. `patterns` are case-insensitive regular-expression source strings (no flags) matched against a single requirement sentence. */
export interface Material {
  key: string;
  label: string;
  patterns: string[];
}

